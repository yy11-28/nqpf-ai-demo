const Lc = (() => {
  let lang = 'zh';
  let theme = 'dark';

  const storage = {
    get(k, d) { try { return localStorage.getItem(k) || d; } catch (e) { return d; } },
    set(k, v) { try { localStorage.setItem(k, v); } catch (e) {} },
  };

  function apply() {
    document.documentElement.setAttribute('data-theme', theme);
    const dict = I18N[lang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      if (dict[key]) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.value = dict[key];
        else el.textContent = dict[key];
      }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.dataset.i18nPlaceholder;
      if (dict[key]) el.placeholder = dict[key];
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.dataset.i18nHtml;
      if (dict[key]) el.innerHTML = dict[key].replace(/\n/g, '<br>');
    });
    // 更新 lang 属性（确保 font-variant-numeric 等生效）
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    if (typeof onI18nChange === 'function') onI18nChange(lang, theme);
  }

  function init() {
    theme = storage.get('theme', window.matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark');
    lang = storage.get('lang', 'zh');
    apply();
  }

  return {
    init,
    apply,
    getLang: () => lang,
    getTheme: () => theme,
    toggleTheme() {
      theme = theme === 'dark' ? 'light' : 'dark';
      storage.set('theme', theme);
      apply();
    },
    toggleLang() {
      lang = lang === 'zh' ? 'en' : 'zh';
      storage.set('lang', lang);
      apply();
    },
    t(key) { return I18N[lang][key] || key; },
    en(key) { return I18N.en[key] || key; },
  };
})();

window.Lc = Lc;
